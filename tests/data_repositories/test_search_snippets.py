"""Snippet search on both real engines: ``snippet()`` on SQLite FTS5, ``ts_headline`` on
PostgreSQL.

``memory_repo`` is the engine seat — SQLite in the default suite, the same assertions against
a real PostgreSQL once ``MUNNIN_PG_TEST_URL`` names a disposable test database. Nothing here
is mocked: the excerpt is generated by the engine's own function, which is the whole point of
the change.

The recurring assertions are two: the hit still *exists* (a title-only or tag-only match must
not vanish because the body had no match), and no complete body travels in either field
spelling.
"""

from __future__ import annotations

import pytest

from munnin.data_entities.memory_record import MemoryRecord, RecordType, SharedRecord

BODY = " ".join(["filler"] * 60) + " pangolin lives here " + " ".join(["tail"] * 60)


def _record(uuid: str, *, title: str, content: str, tags: list[str] | None = None):
    return MemoryRecord(
        uuid=uuid, user_id="", agent_id="meta", record_type=RecordType.knowledge,
        title=title, tags=tags or [], full_content=content,
        content_summary="search fixture",
    )


def test_a_body_match_returns_metadata_and_a_bounded_snippet(memory_repo) -> None:
    memory_repo.insert(_record("hit00001", title="A note", content=BODY))
    hits = memory_repo.search_with_snippet("pangolin")
    assert len(hits) == 1
    hit = hits[0]
    assert hit.uuid == "hit00001"
    assert hit.title == "A note"
    assert "pangolin" in hit.snippet
    # An excerpt, not the document: the body is ~880 characters, the window is bounded.
    assert len(hit.snippet) < len(BODY)
    assert hit.agent_id == "meta"


def test_a_title_only_match_still_yields_a_hit_and_a_snippet(memory_repo) -> None:
    """The body says nothing about the term; the title does. It must not disappear."""
    memory_repo.insert(_record("hit00002", title="rollout notes", content="unrelated words"))
    hits = memory_repo.search_with_snippet("rollout")
    assert [hit.uuid for hit in hits] == ["hit00002"]
    assert hits[0].snippet.strip()


def test_a_tag_only_match_still_yields_a_hit_and_a_snippet(memory_repo) -> None:
    memory_repo.insert(
        _record("hit00003", title="A plain note", content="nothing relevant", tags=["aardvark"])
    )
    hits = memory_repo.search_with_snippet("aardvark")
    assert [hit.uuid for hit in hits] == ["hit00003"]
    assert hits[0].snippet.strip()


def test_hyphenated_and_punctuated_bodies_are_found_by_their_terms(memory_repo) -> None:
    """Both engines index the words inside ``foo-bar``/``baz_qux``, which is the behaviour
    the existing parity coverage pins. The *query* side keeps its own engine contract:
    SQLite matches the hyphenated string literally, PostgreSQL's ``plainto_tsquery``
    requires every part — a pre-existing difference this change does not touch."""
    memory_repo.insert(
        _record("hit00004", title="end-to-end", content="foo-bar and baz_qux tokenization")
    )
    for term in ("foo", "bar", "baz", "qux", "tokenization", "end"):
        assert [h.uuid for h in memory_repo.search_with_snippet(term)] == ["hit00004"], term
    # The matched term appears in the excerpt, so the window is on the matching text.
    assert "tokenization" in memory_repo.search_with_snippet("tokenization")[0].snippet


def test_non_ascii_text_round_trips_into_the_snippet(memory_repo) -> None:
    memory_repo.insert(_record("hit00005", title="Une note", content="le caf\u00e9 est na\u00efve"))
    hits = memory_repo.search_with_snippet("caf\u00e9")
    assert [h.uuid for h in hits] == ["hit00005"]
    assert "caf\u00e9" in hits[0].snippet


def test_membership_matches_the_full_entity_search(memory_repo) -> None:
    """The projection changes what travels, not what matches."""
    for uuid, title, content in (
        ("hit00006", "first", "memory belongs here"),
        ("hit00007", "memory in the title", "nothing"),
        ("hit00008", "third", "unrelated body"),
    ):
        memory_repo.insert(_record(uuid, title=title, content=content))
    for query in ("memory", "first", "nothing"):
        full = {row.uuid for row in memory_repo.search(query)}
        snippets = {hit.uuid for hit in memory_repo.search_with_snippet(query)}
        assert full == snippets


def test_no_match_is_an_empty_list(memory_repo) -> None:
    memory_repo.insert(_record("hit00009", title="A note", content="ordinary words"))
    assert memory_repo.search_with_snippet("zzzznotpresent") == []


def test_archived_is_searchable_by_default_and_deleted_never(memory_repo) -> None:
    memory_repo.insert(_record("hit00010", title="Archived", content="wombat"))
    memory_repo.insert(_record("hit00011", title="Deleted", content="wombat"))
    memory_repo.archive("hit00010")
    memory_repo.soft_delete("hit00011")
    assert [h.uuid for h in memory_repo.search_with_snippet("wombat")] == ["hit00010"]
    assert memory_repo.search_with_snippet("wombat", include_archived=False) == []


def test_the_shared_corpus_has_its_own_snippet_read(memory_repo) -> None:
    memory_repo.insert_shared(
        SharedRecord(
            uuid="shared01", user_id="", record_type=RecordType.reasoning,
            title="Slow is fast", full_content="be thorough, always", tags=[],
        )
    )
    hits = memory_repo.search_shared_with_snippet("thorough")
    assert [h.uuid for h in hits] == ["shared01"]
    assert "thorough" in hits[0].snippet
    # The agent corpus read does not see fleet memory, and the reverse holds too.
    assert memory_repo.search_with_snippet("thorough") == []


def test_the_snippet_is_plain_text_on_both_engines(memory_repo) -> None:
    """Neither engine's highlight markup may leak: a prompt is not an HTML document."""
    memory_repo.insert(_record("hit00012", title="Highlight", content="the pangolin again"))
    snippet = memory_repo.search_with_snippet("pangolin")[0].snippet
    assert pangolin_count(snippet) == 1
    for marker in ("<b>", "</b>", "<mark>", "* *"):
        assert marker not in snippet


def pangolin_count(text: str) -> int:
    return text.count("pangolin")


@pytest.mark.parametrize("query", ["", "   "])
def test_a_blank_query_returns_nothing(memory_repo, query: str) -> None:
    memory_repo.insert(_record("hit00013", title="A note", content="words"))
    assert memory_repo.search_with_snippet(query) == []
